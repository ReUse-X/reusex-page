"""Generate themes/reuse-x/assets/css/tailwind-theme.css from the vendored
product tokens (tokens.css) and the site tokens (site-tokens.css).

Tailwind utilities are mapped onto the tokens with `@theme reference`: the
theme keys are registered so bg-accent, text-on-chrome, rounded-md … exist,
but Tailwind emits no values — utilities compile to var(--color-accent) and
tokens.css supplies the value, per theme (light/dark). Tailwind's default
palette, radii, shadows and fonts are switched off, so a class like
bg-gray-500 simply does not exist: tokens only, by construction.

Names that differ between the product and Tailwind (font sizes, line
heights) and the site's own sizes are mapped with `@theme inline`.

Run after scripts/sync-tokens.sh (it calls this). Usage: tailwind-theme.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"],
                           capture_output=True, text=True, check=True).stdout.strip())
CSS = ROOT / "themes/reuse-x/assets/css"


def names(path: Path) -> list[str]:
    seen = []
    for n in re.findall(r"(--[\w-]+)\s*:", re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)):
        if n not in seen:
            seen.append(n)
    return seen


product = names(CSS / "tokens.css")
site = names(CSS / "site-tokens.css")

# Product token families Tailwind understands under the same name.
same_name = [n for n in product if re.match(r"--(color|radius|shadow|font|tracking)-", n)
             and not n.startswith("--font-size-")]

inline = []
for n in product:
    if m := re.match(r"--font-size-([\w-]+)$", n):
        inline.append((f"--text-{m.group(1)}", n))
    elif m := re.match(r"--line-height-([\w-]+)$", n):
        inline.append((f"--leading-{m.group(1)}", n))
for n in site:
    if m := re.match(r"--site-font-size-([\w-]+)$", n):
        inline.append((f"--text-{m.group(1)}", n))
    elif n == "--site-line-height-display":
        inline.append(("--leading-display", n))
    elif n == "--site-line-height-prose":
        inline.append(("--leading-prose", n))
    elif m := re.match(r"--site-width(-[\w-]+)?$", n):
        inline.append((f"--container-site{m.group(1) or ''}", n))
    elif n == "--site-gutter":
        inline.append(("--spacing-gutter", n))
    elif n == "--site-space-section":
        inline.append(("--spacing-section", n))
    elif n == "--site-tap-target":
        inline.append(("--spacing-tap", n))
    elif n == "--site-header-height":
        inline.append(("--spacing-header", n))

out = ["/* GENERATED by scripts/tailwind-theme.py from tokens.css + site-tokens.css",
       "   — do not edit; run the script (or scripts/sync-tokens.sh). */",
       "",
       "/* Same-named product tokens: registered, never redefined (values come",
       "   from tokens.css at run time, per theme). Defaults switched off. */",
       "@theme reference {",
       "  --color-*: initial;",
       "  --radius-*: initial;",
       "  --shadow-*: initial;",
       "  --font-*: initial;",
       "  --font-weight-*: initial;",
       "  --tracking-*: initial;"]
out += [f"  {n}: '';" for n in same_name]
out += ["}", "",
        "/* Renamed product tokens and site tokens. */",
        "@theme inline {",
        "  --text-*: initial;",
        "  --leading-*: initial;"]
out += [f"  {k}: var({v});" for k, v in inline]
out += ["}", ""]
(CSS / "tailwind-theme.css").write_text("\n".join(out))
print(f"tailwind-theme.py: {len(same_name)} referenced + {len(inline)} mapped tokens → "
      f"{(CSS / 'tailwind-theme.css').relative_to(ROOT)}")
